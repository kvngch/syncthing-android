package com.nutomic.syncthingandroid.model;

/**
 * Sources:
 * - https://github.com/syncthing/syncthing/tree/master/lib/config
 * - https://github.com/syncthing/syncthing/blob/master/lib/config/guiconfiguration.go
 */
public class Gui {
    public boolean enabled = true;

    /**
     * REST: useTLS
     * XML: tls
     */
    public boolean useTLS = false;

    public String address = "127.0.0.1:8384";
    public String user;
    public String password;
    public String apiKey;                           // Automatically generated by SyncthingNative

    /**
     * Available: default, dark, black
     */
    public String theme = "default";

    // omitEmpty
    public boolean insecureAdminAccess = false;
    public boolean insecureAllowFrameLoading = false;
    // The JSON name is insecureSkipHostcheck, so Gson skips this field.
    public transient boolean insecureSkipHostCheck = false;

    public String getBindAddress() {
        if (address == null) {
            return "";
        }
        // Split on the last colon: an IPv6 host such as [::1] holds colons too.
        int colon = address.lastIndexOf(':');
        return colon < 0 ? address : address.substring(0, colon);
    }

    public String getBindPort() {
        if (address == null) {
            return "";
        }
        int colon = address.lastIndexOf(':');
        return colon < 0 ? "" : address.substring(colon + 1);
    }
}
