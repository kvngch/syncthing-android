package com.nutomic.syncthingandroid.model

/**
 * Sources:
 * - https://github.com/syncthing/syncthing/tree/main/lib/config
 * - https://github.com/syncthing/syncthing/blob/main/lib/config/optionsconfiguration.go
 */
class Options {
    @JvmField var listenAddresses: Array<String>? = null // json:"listenAddresses" xml:"listenAddress" default:"default"
    @JvmField var globalAnnounceServers: Array<String>? = null // json:"globalAnnounceServers" xml:"globalAnnounceServer" default:"default"
    @JvmField var globalAnnounceEnabled: Boolean = true
    @JvmField var localAnnounceEnabled: Boolean = true
    @JvmField var localAnnouncePort: Int = 21027
    @JvmField var localAnnounceMCAddr: String? = null // [ff12::8384]:21027
    @JvmField var maxSendKbps: Int = 0
    @JvmField var maxRecvKbps: Int = 0
    @JvmField var reconnectionIntervalS: Int = 60
    @JvmField var relaysEnabled: Boolean = true
    @JvmField var relayReconnectIntervalM: Int = 10
    @JvmField var startBrowser: Boolean = false // Normally "true" but makes no sense on Android.
    @JvmField var natEnabled: Boolean = true
    @JvmField var natLeaseMinutes: Int = 60
    @JvmField var natRenewalMinutes: Int = 30
    @JvmField var natTimeoutSeconds: Int = 10
    @JvmField var urAccepted: Int = 0 // 0: Undecided
    @JvmField var urUniqueId: String? = null // Automatically generated by SyncthingNative
    @JvmField var urURL: String = "https://data.syncthing.net/newdata"
    @JvmField var urPostInsecurely: Boolean = false
    @JvmField var urInitialDelayS: Int = 1800
    @JvmField var autoUpgradeIntervalH: Int = 0 // Normally "12" but makes no sense on Android.
    @JvmField var upgradeToPreReleases: Boolean = false
    @JvmField var keepTemporariesH: Int = 24
    @JvmField var cacheIgnoredFiles: Boolean = false
    @JvmField var progressUpdateIntervalS: Int = 5
    @JvmField var limitBandwidthInLan: Boolean = false
    @JvmField var releasesURL: String = "https://upgrades.syncthing.net/meta.json"
    @JvmField var alwaysLocalNets: Array<String>? = null // Still present in SyncthingNative 1.0.1
    @JvmField var overwriteRemoteDeviceNamesOnConnect: Boolean = false
    @JvmField var tempIndexMinBlocks: Int = 10
    @JvmField var setLowPriority: Boolean = true

    // Since v0.14.28
    @JvmField var minHomeDiskFree: MinHomeDiskFree? = null

    // Since v1.2.0
    // json: crURL, xml: crashReportingURL
    @JvmField var crURL: String = "https://crash.syncthing.net/newcrash"
    @JvmField var crashReportingEnabled: Boolean = true
    @JvmField var stunKeepaliveStartS: Int = 180
    @JvmField var stunKeepaliveMinS: Int = 20

    // XML tag name, read and written by ConfigXml only. The JSON name differs, so Gson skips it.
    @Transient @JvmField var stunServer: String = "default"

    // Since v1.4.0
    // See https://github.com/syncthing/syncthing/pull/6290
    @JvmField var maxFolderConcurrency: Int = 1

    // See https://github.com/syncthing/syncthing/pull/6303
    @JvmField var maxConcurrentIncomingRequestKiB: Int = 0

    // Since v1.10.0
    // See https://github.com/syncthing/syncthing/pull/6896
    @JvmField var announceLANAddresses: Boolean = true

    // Since v1.11.0
    // See https://github.com/calmh/syncthing/commit/e57eec8660606fa65fd3080b9c5d98447f54abeb
    @JvmField var sendFullIndexOnUpgrade: Boolean = false

    // Since v1.12.0
    // See https://github.com/syncthing/syncthing/pull/7055
    // XML tag name, read and written by ConfigXml only. The JSON name differs, so Gson skips it.
    @Transient @JvmField var featureFlag: String = ""

    // Since v1.13.0
    @JvmField var connectionLimitEnough: Int = 0
    @JvmField var connectionLimitMax: Int = 0

    // Items that may be temporarily missing because they are empty.
    /**
     * Possible notification IDs:
     * crAutoDisabled                  (crash reporting after upgrade to v1.2.0)
     * crAutoEnabled                   (crash reporting after upgrade to v1.2.0)
     */
    // XML tag name, read and written by ConfigXml only. The JSON name differs, so Gson skips it.
    @Transient @JvmField var unackedNotificationID: String = ""

    class MinHomeDiskFree {
        @JvmField var value: Float = 1f
        @JvmField var unit: String = "%"
    }

    fun isUsageReportingAccepted(urVersionMax: Int): Boolean = urAccepted == urVersionMax

    fun isUsageReportingDecided(urVersionMax: Int): Boolean =
        isUsageReportingAccepted(urVersionMax) || urAccepted == USAGE_REPORTING_DENIED

    companion object {
        const val USAGE_REPORTING_UNDECIDED = 0
        const val USAGE_REPORTING_DENIED = -1
    }
}
